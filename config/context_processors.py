def site_ui(request: Any) -> dict[str, Any]:
    """Expose the selected UI language and text tokens."""
    language = request.session.get("site_language", "uk")
    if language not in UI_TEXTS:
        language = "uk"
    return {
        "site_language": language,
        "language_choices": LANGUAGE_CHOICES,
        "ui": UI_TEXTS[language],
    }
